import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv('/content/insurance.csv')

print("Dataset shape:", df.shape)
print("\nColumn information:")
df.info()

print("\nDescriptive statistics:")
display(df.describe())

print("\nCategorical column values:")
for col in ['sex', 'smoker', 'region']:
    print(f"\n{col}:")
    print(df[col].value_counts())

# Check missing values
print("Missing values before cleaning:")
print(df.isnull().sum())

# Check duplicate rows
print("\nDuplicate rows:", df.duplicated().sum())

# Remove exact duplicate rows, if any
df = df.drop_duplicates().copy()

# Handle missing values only if they exist
numeric_cols = df.select_dtypes(include=np.number).columns
categorical_cols = df.select_dtypes(exclude=np.number).columns

for col in numeric_cols:
    if df[col].isnull().any():
        df[col] = df[col].fillna(df[col].median())

for col in categorical_cols:
    if df[col].isnull().any():
        df[col] = df[col].fillna(df[col].mode()[0])

print("\nMissing values after cleaning:")
print(df.isnull().sum())

print("\nDataset shape after cleaning:", df.shape)

# Identify potential outliers using the IQR method
for col in ['age', 'bmi', 'children', 'charges']:
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1

    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR

    count = ((df[col] < lower) | (df[col] > upper)).sum()

    print(f"{col}: {count} potential outliers")

plt.figure(figsize=(8, 5))
sns.histplot(data=df, x='age', bins=20, kde=True)
plt.title('Distribution of Customer Ages')
plt.xlabel('Age')
plt.ylabel('Number of Customers')
plt.tight_layout()
plt.show()

print("Interpretation: This chart shows the age distribution of customers.")
print("The highest bars indicate the age ranges with the most observations.")

plt.figure(figsize=(8, 5))
sns.boxplot(data=df, x='charges')
plt.title('Distribution and Potential Outliers in Insurance Charges')
plt.xlabel('Insurance Charges ($)')
plt.tight_layout()
plt.show()

print("Interpretation: The boxplot shows the spread of insurance charges.")
print("Points beyond the whiskers are potential outliers, not necessarily errors.")

plt.figure(figsize=(8, 6))
numeric_df = df.select_dtypes(include=np.number)
sns.heatmap(numeric_df.corr(), annot=True, cmap='coolwarm', fmt='.2f')
plt.title('Correlation Between Numerical Variables')
plt.tight_layout()
plt.show()

print("Interpretation: Correlation values range from -1 to +1.")
print("Values closer to +1 indicate stronger positive linear relationships.")
print("Correlation does not establish causation.")

plt.figure(figsize=(8, 5))
sns.barplot(data=df, x='smoker', y='charges', errorbar=None)
plt.title('Average Insurance Charges by Smoking Status')
plt.xlabel('Smoker')
plt.ylabel('Average Insurance Charges ($)')
plt.tight_layout()
plt.show()

print("Interpretation: This chart compares mean insurance charges")
print("between smokers and non-smokers.")

# Feature 1: Categorize BMI
df['bmi_category'] = pd.cut(
    df['bmi'],
    bins=[0, 18.5, 25, 30, float('inf')],
    labels=['Underweight', 'Normal', 'Overweight', 'Obese'],
    right=False
)

# Feature 2: Interaction between age and smoking status
df['smoker_binary'] = df['smoker'].map({'yes': 1, 'no': 0})
df['smoker_age_interaction'] = df['age'] * df['smoker_binary']

print("First five rows with engineered features:")
display(df[['age', 'bmi', 'smoker', 'bmi_category',
            'smoker_age_interaction']].head())

print("\nBMI category counts:")
print(df['bmi_category'].value_counts())

print("\nSmoker-age interaction summary:")
print(df.groupby('smoker')['smoker_age_interaction'].describe())

print("FIVE DATA-BASED FINDINGS")

# Finding 1: Age distribution
print(
    f"1. Customer ages range from {df['age'].min()} to "
    f"{df['age'].max()} years, with a median age of "
    f"{df['age'].median():.1f} years."
)

# Finding 2: Charges distribution
print(
    f"2. Insurance charges have a median of ${df['charges'].median():,.2f} "
    f"and a mean of ${df['charges'].mean():,.2f}."
)

# Finding 3: Smoking comparison
smoking_means = df.groupby('smoker')['charges'].mean()
print("\nAverage charges by smoking status:")
print(smoking_means.round(2))

if {'yes', 'no'}.issubset(smoking_means.index):
    print(
        f"3. Smokers' average charges are "
        f"${smoking_means['yes']:,.2f}, compared with "
        f"${smoking_means['no']:,.2f} for non-smokers."
    )

# Finding 4: BMI and charges relationship
bmi_corr = df['bmi'].corr(df['charges'])
print(
    f"4. The correlation between BMI and insurance charges is "
    f"{bmi_corr:.3f}."
)

# Finding 5: Regional charges
region_means = df.groupby('region')['charges'].mean().sort_values(ascending=False)
print("\nAverage charges by region:")
print(region_means.round(2))

print(
    f"5. The region with the highest average charges is "
    f"{region_means.index[0]}, at ${region_means.iloc[0]:,.2f}."
)









