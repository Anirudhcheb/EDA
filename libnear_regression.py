# Importing Libraries
import numpy as np
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Load Dataset
df = pd.read_csv('/content/WineQT.csv')

# First 5 rows
print(df.head())

# Last 5 rows
print(df.tail())

# Datatypes of the dataset
df.info()

# Statistical representation
print(df.describe())

# Total number of rows and columns
print("Dataset Shape:", df.shape)

# Value counts of quality
print(df['quality'].value_counts())

# Finding missing values
print(df.isnull().sum())

# Initial observations:
# The dataset contains numerical wine features and a quality target.
# The dataset shape, data types, statistical ranges and quality distribution
# are inspected before preprocessing.

# Separate features and target
x = df.drop(columns=['quality'])
y = df['quality']

# Train Test Split
from sklearn.model_selection import train_test_split

x_train, x_test, y_train, y_test = train_test_split(
    x, y, test_size=0.2, random_state=42
)

# Create copies
x_train = x_train.copy()
x_test = x_test.copy()

# Handle missing values using training median
mv = x_train['alcohol'].median()

x_train['alcohol'] = x_train['alcohol'].fillna(mv)
x_test['alcohol'] = x_test['alcohol'].fillna(mv)

# Handle outliers using IQR
q1 = x_train['alcohol'].quantile(0.25)
q3 = x_train['alcohol'].quantile(0.75)

iqr = q3 - q1

# Correct lower and upper bounds
low = q1 - 1.5 * iqr
up = q3 + 1.5 * iqr

# Clip using training bounds
x_train['alcohol'] = x_train['alcohol'].clip(
    lower=low, upper=up
)

x_test['alcohol'] = x_test['alcohol'].clip(
    lower=low, upper=up
)

print("Lower Bound:", low)
print("Upper Bound:", up)

# Boxplot after handling outliers
sns.boxplot(x=x_train['alcohol'])
plt.title("Alcohol After Outlier Handling")
plt.show()

# Display preprocessed data
print(x_train.head())

# Linear Regression
from sklearn.linear_model import LinearRegression

lr = LinearRegression()
lr.fit(x_train, y_train)

lr_pred = lr.predict(x_test)

# Ridge and Lasso Regression
from sklearn.linear_model import Ridge, Lasso

rd = Ridge(alpha=1.0)
ls = Lasso(alpha=1.0)

rd.fit(x_train, y_train)
rd_pred = rd.predict(x_test)

ls.fit(x_train, y_train)
ls_pred = ls.predict(x_test)

# Coefficient Comparison
coefficients = pd.DataFrame(
    {
        'Linear': lr.coef_,
        'Ridge': rd.coef_,
        'Lasso': ls.coef_
    },
    index=x_train.columns
)

print("\nCoefficient Comparison:")
print(coefficients)

# Evaluation Metrics
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

# Linear Regression Metrics
lr_mae = mean_absolute_error(y_test, lr_pred)
lr_mse = mean_squared_error(y_test, lr_pred)
lr_rmse = np.sqrt(lr_mse)
lr_r2 = r2_score(y_test, lr_pred)

# Ridge Regression Metrics
rd_mae = mean_absolute_error(y_test, rd_pred)
rd_mse = mean_squared_error(y_test, rd_pred)
rd_rmse = np.sqrt(rd_mse)
rd_r2 = r2_score(y_test, rd_pred)

# Lasso Regression Metrics
ls_mae = mean_absolute_error(y_test, ls_pred)
ls_mse = mean_squared_error(y_test, ls_pred)
ls_rmse = np.sqrt(ls_mse)
ls_r2 = r2_score(y_test, ls_pred)

# Create Metrics Comparison Table
metrics_df = pd.DataFrame(
    {
        'Linear Regression': [
            lr_mae, lr_mse, lr_rmse, lr_r2
        ],
        'Ridge Regression': [
            rd_mae, rd_mse, rd_rmse, rd_r2
        ],
        'Lasso Regression': [
            ls_mae, ls_mse, ls_rmse, ls_r2
        ]
    },
    index=['MAE', 'MSE', 'RMSE', 'R2']
)

print("\nRegression Models Performance Comparison:")
print(metrics_df)

# Identify Best Model
best_model = metrics_df.loc['R2'].idxmax()

print("\nConclusion:")
print("Best Generalizing Model:", best_model)

print(
    "The model with the highest test R2 score provides the best "
    "explained variance among the three models."
)

print(
    "Ridge regularization reduces coefficient magnitudes, while "
    "Lasso can shrink some coefficients to zero. These changes "
    "help control model complexity."
)

print(
    "The MAE, MSE and RMSE values should also be compared. "
    "Lower values indicate smaller prediction errors."
)









